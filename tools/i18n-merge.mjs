// Builds src/i18n/en.js from a numbered todo list and numbered English lines.
//   node tools/i18n-merge.mjs todo.tsv en_1.tsv en_2.tsv ... [extra.tsv]
// todo.tsv:  N<TAB>"indonesian (JSON)"      en_*.tsv: N<TAB>english (\n = newline)
// extra.tsv: indonesian<TAB>english (keys that are not numbered)
import fs from 'node:fs';
const [todoFile, ...rest] = process.argv.slice(2);
const todo = new Map(fs.readFileSync(todoFile, 'utf8').split('\n').filter(Boolean).map((l) => { const i = l.indexOf('\t'); return [Number(l.slice(0, i)), JSON.parse(l.slice(i + 1))]; }));
const EN = {};
let used = 0, missing = [];
for (const f of rest) {
  for (const line of fs.readFileSync(f, 'utf8').split('\n')) {
    if (!line.trim()) continue;
    const tab = line.indexOf('\t');
    const head = line.slice(0, tab), val = line.slice(tab + 1).replace(/\\n/g, '\n');
    if (/^\d+$/.test(head)) {
      const id = Number(head), key = todo.get(id);
      if (key === undefined) { missing.push(id); continue; }
      if (key !== val) EN[key] = val;
      used++;
    } else if (head) EN[head.replace(/\\n/g, '\n')] = val;
  }
}
// keep any hand-written entries already in en.js
let existing = {};
try { existing = (await import('../src/i18n/en.js?' + Date.now())).EN; } catch { /* first run */ }
const merged = { ...existing, ...EN };
const body = Object.entries(merged).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n');
fs.writeFileSync(new URL('../src/i18n/en.js', import.meta.url), `// English translations (generated by tools/i18n-merge.mjs, then maintained by hand).\n// Key = the Indonesian source text exactly; {1}, {2} are positional arguments.\nexport const EN = {\n${body}\n};\n`);
console.log('numbered lines used:', used, '· entries:', Object.keys(merged).length, '· unknown ids:', missing.join(','));
